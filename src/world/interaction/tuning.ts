// 互動目標選擇的三個係數。**每一個都是量出來的，量測結果寫在下面。**
//
// 規格刻意沒有寫死這三個數字（`FE-W06` design 的 Q1～Q3）——
// 把猜出來的數字寫進 Requirement 之後，實作只會回頭改那個數字。

export const TUNING: TargetTuning = {
  /**
   * 互動範圍的半徑（世界單位）。
   *
   * **`FE-W12` 已經回來重量了**（那一項有六扇門與兩塊看板的實際尺寸）。
   * 值沒有改，但它現在**有依據**：
   *
   *     range   貼著站  退一步(1.0)   出生點誤觸
   *     0.3     6/8     0/8           否
   *     0.4     8/8     0/8           否
   *     1.0     8/8     0/8           否
   *     1.5     8/8     8/8           否     ← 下界
   *     2.0     8/8     8/8           否
   *     6.0     8/8     8/8           否
   *     7.0     8/8     8/8           **是** ← 上界在 6.52
   *
   * **下界 1.5**：只驗「最近的可站立格選得到」的話 0.4 就夠 ——
   * 而 0.4 的意思是「必須貼著門站」。玩家不會那樣站，所以判準是**退一步**。
   * 門最近的可站立格離門 0.11、看板 0.32，加上一步就是 1.11／1.32。
   *
   * **上界 6.52**：出生點 `(0, -1)` 到最近的看板 `(±3.5, -6.5)` 是
   * `hypot(3.5, 5.5) = 6.52` —— 超過的話一出生畫面上就掛著
   * 「按 E 看專案看板」，而那個提示永遠不會消失。
   *
   * ⚠️ **這個上界第一次量錯了**：我只看了 z 的差（5.5），漏掉 x 的 3.5。
   * 突變 `range = 6` 因此是綠的。真正的界線是 6.52，`range = 7` 才紅。
   *
   * 2 離兩邊都夠遠。判準在 `tests/world-rooms-reachable.test.tsx`，
   * **它走的是真實的 `SpatialInteraction`**，不是座標算術。
   */
  range: 2,

  /**
   * 朝向在分數裡的權重。分數是 `facingWeight × 對齊度 + 接近度`，
   * 對齊度 ∈ [-1, 1]、接近度 ∈ [0, 1]。
   *
   * 量出來的（design 的 Q3，兩個判準情況）：
   *
   *     w      (i) 貼著 A、面向遠處的 B   (ii) 兩個等距、面向其中一個
   *     0.1    → A  ✅                    → 面向的那個  ✅
   *     0.2    → A  ✅                    → ✅
   *     0.3    → A  ✅                    → ✅
   *     0.4    → B  ❌ 選到遠的那個        → ✅
   *     1.0    → B  ❌                    → ✅
   *
   * **失敗從 0.4 開始**（代數上的臨界值是 0.375，跟那組位置有關）。
   * 取 0.25 是為了離臨界值遠一點 —— 不同的物件配置會讓臨界值移動。
   *
   * 太大的症狀是「站在一個物件正上方，提示卻指著遠處那個」。
   */
  facingWeight: 0.25,

  /**
   * 切換目標需要的分數優勢。
   *
   * ⚠️ **這一項防的是閃爍，不是不決定性**（design 的 D3）。
   *
   * 量出來的（design 的 Q1，120 幀在等分數線附近逐幀來回，數切換次數）：
   *
   *     每幀來回幅度   h=0   h=0.005   h=0.01   h=0.02   h=0.05
   *     0.0667         120   120       120      120      1      ← 一幀的走路距離
   *     0.02           120   120       120      1        1
   *     0.005          120   1         1        1        1
   *
   * 需要的遲滯大約是震盪幅度的四分之三。最壞的實際情況是
   * **一整幀的走路距離**（`MOVE_SPEED` 4 單位／秒 ÷ 60 幀 ≈ 0.0667），
   * 需要 0.05。取兩倍。
   *
   * **太大也是錯的**：轉身要換目標時，朝向帶來的分數差是
   * `facingWeight × 2 = 0.5`，所以遲滯 MUST 明顯小於 0.5，
   * 否則「轉身選另一個」會失效。0.1 離兩邊都夠遠。
   */
  hysteresis: 0.1,
}
